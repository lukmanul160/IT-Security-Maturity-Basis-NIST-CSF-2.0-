const express = require('express');
const controller = require('../controllers/tprmQuestionnaireController');
const { requirePermission, requirePageAccess } = require('../middleware/permission');
const router = express.Router();
const multer = require('../middleware/configuredUpload');
const upload = multer({storage:multer.memoryStorage(),limits:{fileSize:8*1024*1024,files:1,fields:2},fileFilter(req,file,done){if(!/\.xlsx$/i.test(file.originalname))return done(Object.assign(new Error('Gunakan file Excel .xlsx hasil export sistem.'),{status:400}));done(null,true);}});
router.get('/:id/excel', requirePermission('tprm-questionnaire','read'), controller.exportExcel);
router.post('/:id/excel/preview', requirePageAccess('tprm-questionnaire','update'), upload.single('file'), controller.previewExcel);
router.post('/:id/excel', requirePageAccess('tprm-questionnaire','update'), upload.single('file'), controller.importExcel);
router.get('/', requirePermission('tprm-questionnaire', 'read'), controller.list);
router.post('/', requirePageAccess('tprm-questionnaire', 'create'), controller.create);
router.put('/:id', requirePageAccess('tprm-questionnaire', 'update'), controller.update);
router.put('/:id/documents', requirePageAccess('tprm-questionnaire', 'update'), controller.updateDocuments);
router.delete('/:id', requirePageAccess('tprm-questionnaire', 'delete'), controller.remove);
router.use((error,req,res,next)=>error instanceof multer.MulterError ? res.status(400).json({error:'Upload Excel tidak valid. Maksimum 1 file .xlsx berukuran 8 MB.'}) : next(error));
module.exports = router;
