const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const service = require('../src/services/policyDocumentService');
const { pool } = require('../src/config/database');
const storage = require('../src/services/storageService');
const access = require('../src/services/evidenceAccessService');
const permissions = require('../src/services/permissionService');

test('Word editing checks draft status, stale revisions, file ownership and saves a separate version', async t => {
  const file = { originalname: 'policy.docx', buffer: await require('../src/services/statementDocumentService').plain('Edited policy') };
  const row = { id: 1, approval_status: 'Draft', attachment_name: 'policy.docx', attachment_path: 'policy-register/original.docx', document_revision: 'revision-1' };
  const statements = [], stored = [];
  const query = async (sql, args) => { statements.push([sql, args]); return { rows: sql.startsWith('SELECT') ? [{ ...row }] : [] }; };
  t.mock.method(pool, 'query', query);
  t.mock.method(pool, 'connect', async () => ({ query, release() {} }));
  t.mock.method(storage, 'read', async () => file.buffer);
  t.mock.method(storage, 'put', async (...args) => stored.push(args));
  t.mock.method(access, 'assertAccess', async () => true);
  t.mock.method(access, 'userId', async () => 1);
  t.mock.method(permissions, 'hasFileAction', async () => true);
  const user = { role: 'editor' };
  assert.equal((await service.load(1, user)).revision, 'revision-1');
  await assert.rejects(() => service.save(1, user, file, 'old-revision'), { status: 409 });
  assert.equal(stored.length, 0);
  row.approval_status = 'Approved';
  await assert.rejects(() => service.load(1, user), { status: 409 });
  await assert.rejects(() => service.save(1, user, file, 'revision-1'), { status: 409 });
  assert.equal(stored.length, 0);
  row.approval_status = 'Draft'; row.attachment_name = 'policy.doc';
  await assert.rejects(() => service.load(1, user), { status: 400 });
  row.attachment_name = 'policy.docx';
  t.mock.method(access, 'assertAccess', async () => { throw Object.assign(Error('Forbidden'), { status: 403 }); });
  await assert.rejects(() => service.save(1, user, file, 'revision-1'), { status: 403 });
  assert.equal(stored.length, 0);
  t.mock.method(access, 'assertAccess', async () => true);
  assert.deepEqual(await service.save(1, user, file, 'revision-1'), { saved: true });
  assert.equal(stored.length, 1); assert.notEqual(stored[0][0], row.attachment_path);
  assert.deepEqual(stored[0][1].buffer, file.buffer);
  assert.ok(statements.some(([sql]) => sql.includes('FOR UPDATE')));
  assert.ok(statements.some(([sql, args]) => sql.startsWith('UPDATE') && args[1] === stored[0][0]));
  t.mock.method(permissions, 'hasFileAction', async () => false);
  await assert.rejects(() => service.save(1, user, file, 'revision-1'), { status: 403 });
});

test('document routes deny users without Policy Update permission before reading or uploading', async t => {
  t.mock.method(require('../src/services/websiteSettingsService'), 'read', async () => ({}));
  let allowed = false, reads = 0, saves = 0;
  t.mock.method(permissions, 'has', async (_role, module, action) => module === 'policy-register' && (action === 'read' || allowed));
  t.mock.method(service, 'load', async () => { reads++; return { buffer: Buffer.from('DOCX'), name: 'policy.docx', revision: 'v1' }; });
  t.mock.method(service, 'save', async () => { saves++; return { saved: true }; });
  const app = express(); app.use((req, res, next) => { req.user = { role: 'viewer' }; next(); });
  app.use('/policy', require('../src/routes/policyRegisterRoutes'));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const url = `http://127.0.0.1:${server.address().port}/policy/1/document`;
  assert.equal((await fetch(url)).status, 403);
  assert.equal((await fetch(url, { method: 'PUT' })).status, 403);
  assert.equal(reads + saves, 0);
  allowed = true;
  const response = await fetch(url); assert.equal(response.status, 200); assert.equal(response.headers.get('x-document-revision'), 'v1');
  const body = new FormData(); body.set('revision', 'v1'); body.set('document', new Blob(['doc']), 'policy.docx');
  assert.equal((await fetch(url, { method: 'PUT', body })).status, 200);
  assert.equal(reads, 1); assert.equal(saves, 1);
});
